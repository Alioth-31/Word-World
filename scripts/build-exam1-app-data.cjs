'use strict';
const fs=require('node:fs');
const path=require('node:path');
function project(report) {
  if(report.schema!==1 || report.scope.years.join(',')!==Array.from({length:16},(_,i)=>2010+i).join(','))throw Error('Unexpected English I report scope');
  const seen=new Set();
  const rows=report.words.map(w=>{
    if(typeof w.word!=='string'||!w.word||seen.has(w.word))throw Error('Invalid or duplicate word');
    seen.add(w.word);
    if(![w.exact,w.inferred,w.years].every(n=>Number.isSafeInteger(n)&&n>=0)||w.years>16)throw Error('Invalid frequency: '+w.word);
    if((w.exact+w.inferred===0)!==(w.estimatedRank===null)||w.estimatedRank!==null&&(!Number.isSafeInteger(w.estimatedRank)||w.estimatedRank<1))throw Error('Invalid rank: '+w.word);
    return [w.word,w.exact,w.inferred,w.years,w.estimatedRank];
  });
  if(rows.length!==5530)throw Error('Unexpected vocabulary size');
  return {schema:1,years:report.scope.years,revision:report.source.revision,rows};
}
function render(report) {
  return '/* Generated by scripts/build-exam1-app-data.cjs; aggregate counts, not exam text. */\nwindow.WORD_WORLD_EXAM1 = '+JSON.stringify(project(report))+';\n';
}
if(require.main===module){
  const root=path.resolve(__dirname,'..');
  const report=JSON.parse(fs.readFileSync(path.join(root,'data/exam1-frequency.json'),'utf8'));
  fs.writeFileSync(path.join(root,'app/data/exam1.js'),render(report));
}
module.exports={project,render};
